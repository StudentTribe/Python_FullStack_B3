# sorting

bag = ["milk" , "bread" , "eggs" , "sugar" , "curd"]

print(bag)
print(sorted(bag))
print(bag)
print("===========================================")
bag.sort()
print(bag)
print("===========================================")
bag.sort(reverse = True)
print(bag)
print("===========================================")
bag[0] = "mango"
print(bag)